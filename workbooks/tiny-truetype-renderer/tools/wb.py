def parse_args(checkpoint: str, extra=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--out", type=Path, default=Path("tests") / checkpoint)
    ap.add_argument("--ref", type=Path, default=Path("build") / f"ref_p{checkpoint}.exe",
                    help="reference program, for checkpoints whose expected output is a picture")
    if extra:
        extra(ap)
    args = ap.parse_args()
    args.out = args.out if args.out.is_absolute() else ROOT / args.out
    args.ref = args.ref if args.ref.is_absolute() else ROOT / args.ref
    return args


def rel(path: Path) -> str:
    return Path(path).resolve().relative_to(ROOT).as_posix()


def num(v) -> str:
    """Numbers as the expected outputs print them: integers plainly, others to 4 places."""
    v = float(v)
    if v == int(v):
        return str(int(v))
    return f"{v:.4f}".rstrip("0").rstrip(".")


class Cases:
    """Writes <out>/cases.txt (the format tools/check.py reads) plus data files."""

    def __init__(self, out_dir: Path, seed: int, compare: str, requirements, explain: str = "",
                 source: str = FT):
        self.out_dir = Path(out_dir)
        self.out_dir.mkdir(parents=True, exist_ok=True)
        self.lines = [f"# Generated by {Path(sys.argv[0]).name} - do not edit by hand.",
                      f"source {source}", f"seed {seed}", f"compare {compare}"]
        if explain:
            self.lines.append(f"explain {explain}")
        self.lines += [f"requirement {rid} {text}" for rid, text in requirements]
        self.ids = set()

    def add(self, case_id, req, title, input_lines, expected=None, expected_file=None, source=None):
        assert case_id not in self.ids, f"duplicate case id {case_id}"
        assert (expected is None) != (expected_file is None)
        self.ids.add(case_id)
        self.lines += [f"case {case_id} {req}", f"title {title}"]
        if source:
            self.lines.append(f"source {source}")
        self.lines += ["input", *input_lines]
        if expected_file is not None:
            self.lines.append(f"expected-file {rel(expected_file)}")
        else:
            text = expected if isinstance(expected, str) else "\n".join(expected)
            self.lines += ["expected", *text.split("\n")]
        self.lines.append("end")

    def data_file(self, name: str, data: bytes) -> str:
        path = self.out_dir / "data" / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        return rel(path)

    def image_path(self, case_id: str) -> Path:
        path = self.out_dir / "expected" / f"{case_id}.png"
        path.parent.mkdir(parents=True, exist_ok=True)
        return path

    def save(self):
        (self.out_dir / "cases.txt").write_text("\n".join(self.lines) + "\n", encoding="utf-8")
        print(f"wrote {rel(self.out_dir / 'cases.txt')}: {len(self.ids)} cases", file=sys.stderr)


def run_reference(exe: Path, input_lines, out_path: Path):
    """Runs the reference program on `input_lines`, writing its output to out_path."""
    if not Path(exe).exists():
        sys.exit(f"reference program {exe} not found - build it first (cmake --build build --target ...)")
    with tempfile.TemporaryDirectory() as tmp:
        inp = Path(tmp) / "case.in"
        inp.write_text("\n".join(input_lines) + "\n", encoding="utf-8")
        proc = subprocess.run([str(exe), str(inp), str(out_path)], cwd=ROOT, capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f"reference program failed: {proc.stderr.strip()}")


# ---- Fonts ----------------------------------------------------------------------

def load(font_rel: str) -> TTFont:
    return TTFont(ROOT / font_rel)


def glyph_record(font: TTFont, gid: int):
    """(absolute offset, length) of a glyph's record in the file."""
    loca = font["loca"]
    return font.reader.tables["glyf"].offset + loca[gid], loca[gid + 1] - loca[gid]


def outline_of(font: TTFont, name: str):
    """(endPts, [(x, y, on)]) of a glyph; fontTools flattens compound glyphs."""
    glyf = font["glyf"]
    coords, ends, flags = glyf[name].getCoordinates(glyf)
    return list(ends), [(x, y, int(f & 1)) for (x, y), f in zip(coords, flags)]


def outline_lines(ends, points, keyword="outline"):
    """Input/output lines for one outline in the shared text format."""
    lines = [keyword] if keyword else []
    lines.append("ends" + "".join(f" {e}" for e in ends))
    lines.append("points" + "".join(f" {num(x)} {num(y)} {'on' if on else 'off'}" for x, y, on in points))
    return lines


def draw_outline(pen, ends, points):
    """Draws a TrueType-style outline (implied on-curve points included) into a fontTools pen."""
    pp = PointToSegmentPen(pen)
    start = 0
    for end in ends:
        contour = points[start:end + 1]
        pp.beginPath()
        for i, (x, y, on) in enumerate(contour):
            prev_on = contour[i - 1][2]
            pp.addPoint((x, y), segmentType=("line" if prev_on else "qcurve") if on else None)
        pp.endPath()
        start = end + 1


def inside(ends, points, x, y, even_odd: bool) -> bool:
    """Is (x, y) inside the outline? fontTools' PointInsidePen, independent of our code."""
    pen = PointInsidePen(None, (x, y), evenOdd=even_odd)
    draw_outline(pen, ends, points)
    return pen.getResult()


def simple_glyph(contours, program: bytes = b"") -> Glyph:
    """A glyf Glyph from contours given as lists of (x, y, on)."""
    g = Glyph()
    pts = [p for c in contours for p in c]
    ends, n = [], 0
    for c in contours:
        n += len(c)
        ends.append(n - 1)
    g.numberOfContours = len(contours)
    g.endPtsOfContours = ends
    g.coordinates = GlyphCoordinates([(x, y) for x, y, _ in pts])
    g.flags = array("B", [on for _, _, on in pts])
    g.program = ttProgram.Program()
    g.program.fromBytecode(program)
    return g


def compound_glyph(components) -> Glyph:
    """components: [(glyph name, (a, b, c, d, e, f)[, extra flag bits])] meaning
    x' = a*x + c*y + e, y' = b*x + d*y + f. fontTools picks WE_HAVE_A_SCALE /
    X_AND_Y / TWO_BY_TWO and byte vs word arguments when it compiles; `extra`
    may add USE_MY_METRICS (0x200) or SCALED_COMPONENT_OFFSET (0x800)."""
    g = Glyph()
    g.numberOfContours = -1
    g.components = []
    for spec in components:
        name, (a, b, c, d, e, f) = spec[0], spec[1]
        comp = GlyphComponent()
        comp.glyphName, comp.x, comp.y = name, e, f
        comp.flags = spec[2] if len(spec) > 2 else 0
        if (a, b, c, d) != (1, 0, 0, 1):
            comp.transform = [[a, b], [c, d]]
        g.components.append(comp)
    return g


def build_font(path: Path, glyphs: dict, order: list, cmap: dict, advances: dict,
               ascent=800, descent=-200, cmap_subtables=None):
    """Builds a small TrueType font with fontTools.

    glyphs: name -> Glyph (see simple_glyph / compound_glyph); missing names are empty.
    cmap: code point -> name, written as fontTools chooses (format 4, plus 12 if needed),
    unless cmap_subtables = [(platformID, encodingID, format, {cp: name})] is given.
    advances: name -> advance width (lsb is computed from the outline).
    """
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    empty = TTGlyphPen(None).glyph()
    fb.setupGlyf({name: glyphs.get(name, empty) for name in order})
    glyf = fb.font["glyf"]
    metrics = {}
    for name in order:
        g = glyf[name]
        g.recalcBounds(glyf)
        metrics[name] = (advances.get(name, 500), getattr(g, "xMin", 0) if g.numberOfContours else 0)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ascent, descent=descent)
    fb.setupNameTable({"familyName": "Workbook Test", "styleName": "Regular"})
    fb.setupOS2()
    fb.setupPost()
    if cmap_subtables is not None:
        table = table__c_m_a_p()
        table.tableVersion = 0
        table.tables = []
        for platform, encoding, fmt, mapping in cmap_subtables:
            st = CmapSubtable.newSubtable(fmt)
            st.platformID, st.platEncID, st.language = platform, encoding, 0
            st.cmap = dict(mapping)
            table.tables.append(st)
        fb.font["cmap"] = table
    path.parent.mkdir(parents=True, exist_ok=True)
    fb.save(str(path))
    return TTFont(path)
